"""Field reports from forum / news posts: structured observations, absences included.

Turns scraped posts (``data/processed/web_posts.parquet``, ``web_news.parquet``; local only, never committed) into one
row per field report in ``data/processed/field_reports.parquet`` (derived facts only -- no post text):

    post_id, source, date_posted, date_observed (+ uncertainty), is_field_report, report_kind
    (outing | secondhand | status), jurcki_outcome (found | none | few | many | unclear | not_mentioned),
    other_mushrooms_outcome, quantity, location (matcher fields + ellipse), elevation, habitat, a short neutral
    English paraphrase and the labeler (``llm`` = reference label read by a person-equivalent, ``rules`` = this module).

Pieces
* ``load_sources`` / ``select_candidates``  - unified frame and the prefilter (posts worth reading).
* ``read_labels``                           - reference labels, ``data/interim/labels/batch_*.jsonl`` (resumable).
* ``classify_rules``                        - the offline rule classifier: regex features (Slovenian negations,
  diacritic-less spellings, thread context) + a small multinomial logistic model whose weights live in
  ``reports_weights.py`` (generated by ``fit_weights`` / ``--refit``; fitted on the development buckets only).
  Dates (včeraj / v nedeljo / pred tednom), quantity, elevation and habitat are plain regexes; locations come from
  ``jurcki.geo`` (context filtered, threshold tuned on the development labels).
* ``build_reports`` / ``rules_vs_labels`` / ``agreement`` / ``summarize`` - the parquet, agreement statistics, summary.

CLI (no network)::

    python -m jurcki.model.reports            # rebuild: reference labels where present, rules for every other candidate
    python -m jurcki.model.reports --no-labels --out /tmp/x.parquet   # rules only
    python -m jurcki.model.reports --eval     # rules vs labels, development and held-out split (post_id hash % 3 == 0)
    python -m jurcki.model.reports --refit    # refit the weights (needs scikit-learn)

Known limits (see the agreement numbers printed by ``--eval``): the rules detect field reports with F1 about 0.75 and
get the coarse jurčki outcome (present / none / other) right about 77 % of the time on held-out posts; the finer
few / found / many split and "none" recall (about 50 %) are weak -- use the reference labels where they exist.
"""
