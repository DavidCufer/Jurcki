_PARA_CUT = re.compile(r"[,;:]| - | but | and | while | with | after | although | so | as ")
_PARA_STOP = {"and", "but", "the", "of", "a", "an", "to", "in", "on", "at", "for", "with", "by", "from", "as", "so", "while", "after",
              "than", "or", "that", "which", "is", "are", "was", "were", "no", "not", "only", "very", "more", "most",
              "recent", "last", "this", "next", "few", "several", "some", "many", "one", "two", "about", "around", "into", "over"}


def shorten_paraphrase(p: str | None, max_words: int = 15) -> str:
    """At most ``max_words`` words.  Keeps the first clause (setting) and the last clause (usually the result, e.g.
    'no boletes') and drops the longest clauses in between; falls back to a cut at a clause boundary."""
    words = (p or "").split()
    if len(words) <= max_words:
        return " ".join(words)
    parts = [x for x in re.split(r"(?<=[,;:])\s+", " ".join(words)) if x]
    clean = lambda ps: "; ".join(x.rstrip(" ,;:-.") for x in ps) + "."
    while len(parts) > 2 and len(clean(parts).split()) > max_words:
        parts.pop(max(range(1, len(parts) - 1), key=lambda k: len(parts[k].split())))
    out = clean(parts)
    if len(out.split()) <= max_words:
        return out
    head = " ".join(words[:max_words])
    cuts = [m.start() for m in _PARA_CUT.finditer(head) if len(head[:m.start()].split()) >= 6]
    if cuts:
        head = head[:cuts[-1]]
    w = head.rstrip(" ,;:-.").split()
    while len(w) > 3 and w[-1].lower().strip(",;:") in _PARA_STOP:
        w.pop()
    return " ".join(w).rstrip(" ,;:-") + "."


def build_reports(labels_dir: Path = LABELS_DIR, posts_path: Path = POSTS_PATH, news_path: Path = NEWS_PATH,
                  use_labels: bool = True, out_path: Path | None = None, verbose: bool = False) -> pd.DataFrame:
    """Merge reference (llm) labels with rule predictions into one frame of field reports (no post text).

    Posts that carry a reference label use it (``labeler == "llm"``); every other candidate post is classified by the
    rules (``labeler == "rules"``).  Only rows with ``report_kind != "none"`` are returned.
    """
    from ..geo import best_location
    df = load_sources(posts_path, news_path)
    cand = select_candidates(df)
    labels = read_labels(labels_dir).set_index("post_id") if use_labels else pd.DataFrame(columns=LABEL_FIELDS).set_index("post_id")
    ids = list(dict.fromkeys(list(cand["post_id"]) + [i for i in labels.index if i in set(df["post_id"])]))
    byid = df.set_index("post_id", drop=False)
    rows = []
    n_geo_fail: dict[str, int] = {}
    for k, pid in enumerate(ids):
        r = byid.loc[pid]
        rule = classify_rules(r.text, r.thread_title, r.board, r.source, r.date_posted)
        lab = labels.loc[pid] if pid in labels.index else None
        if lab is not None:
            kind, jo, oo = lab.report_kind, lab.jurcki_outcome, lab.other_mushrooms_outcome
            qv, qu = lab.quantity_value, lab.quantity_unit
            off, unc = int(lab.date_offset_days), int(lab.date_uncertainty_days)
            elev, hab, para, who = lab.elev_m, lab.habitat, shorten_paraphrase(lab.paraphrase), "llm"
        else:
            kind, jo, oo = rule.report_kind, rule.jurcki_outcome, rule.other_mushrooms_outcome
            qv, qu, off, unc = rule.quantity_value, rule.quantity_unit, rule.date_offset_days, rule.date_uncertainty_days
            elev, hab, para, who = rule.elev_m, rule.habitat, "", "rules"
        if kind == "none":
            continue
        loc, loc_src, loc_text = None, None, None
        if lab is not None:
            if lab.loc_mode == "matcher":
                loc, loc_src = best_location(r.text), "matcher"
            elif lab.loc_mode == "text":
                loc_text = lab.loc_text
                loc, loc_src = geocode_place(lab.loc_text), "label_text"
                if loc is not None and loc.confidence < LABEL_LOC_MIN_CONF:
                    loc = None
                if loc is None:
                    n_geo_fail[lab.loc_text] = n_geo_fail.get(lab.loc_text, 0) + 1
        else:
            loc, loc_src = rule_location(r.text), "rules"
        dp = pd.Timestamp(r.date_posted)
        row = dict(post_id=pid, source=r.source, date_posted=dp.normalize(),
                   date_observed=(dp + pd.Timedelta(days=off)).normalize(), date_uncertainty_days=unc,
                   is_field_report=kind in ("outing", "secondhand"), report_kind=kind, jurcki_outcome=jo,
                   other_mushrooms_outcome=oo, quantity_value=qv, quantity_unit=qu, loc_text=loc_text,
                   elev_m=elev, habitat=hab, paraphrase=para, labeler=who,
                   rules_report_kind=rule.report_kind, rules_jurcki_outcome=rule.jurcki_outcome)
        row.update(_loc_fields(loc, loc_src))
        row["region"] = region_of(row["loc_lon"], row["loc_lat"]) if loc is not None else ""
        rows.append(row)
        if verbose and k % 1000 == 0:
            print(f"  {k}/{len(ids)}", file=sys.stderr)
    out = pd.DataFrame(rows, columns=OUT_COLUMNS)
    out["elev_m"] = pd.to_numeric(out["elev_m"]).astype("Float64")
    out["quantity_value"] = pd.to_numeric(out["quantity_value"])
    out.attrs["geocode_failures"] = n_geo_fail
    if verbose and n_geo_fail:
        print("loc_text not found in the gazetteer (count):", dict(sorted(n_geo_fail.items(), key=lambda kv: -kv[1])), file=sys.stderr)
    if out_path is not None:
        Path(out_path).parent.mkdir(parents=True, exist_ok=True)
        out.to_parquet(out_path, index=False)
    return out


