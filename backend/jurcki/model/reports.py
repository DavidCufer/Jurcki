def region_of(lon: float, lat: float) -> str:
    if lon != lon or lat != lat:
        return ""
    return min(REGION_CENTRES, key=lambda r: (lat - REGION_CENTRES[r][0]) ** 2 + ((lon - REGION_CENTRES[r][1]) * 0.7) ** 2)


