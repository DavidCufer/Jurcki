def _softmax_pick(model: dict[str, dict[str, float]], f: dict[str, float]) -> tuple[str, dict[str, float]]:
    sc = {c: sum(w * f.get(k, 0.0) for k, w in ws.items()) for c, ws in model.items()}
    m = max(sc.values())
    ex = {c: math.exp(v - m) for c, v in sc.items()}
    z = sum(ex.values())
    p = {c: v / z for c, v in ex.items()}
    return max(p, key=p.get), p


@dataclass
class RuleResult:
    report_kind: str = "none"
    jurcki_outcome: str = "not_mentioned"
    other_mushrooms_outcome: str = "unclear"
    quantity_value: float | None = None
    quantity_unit: str | None = None
    elev_m: int | None = None
    habitat: str | None = None
    date_offset_days: int = 0
    date_uncertainty_days: int = 1
    score: float = 0.0          # model probability of the chosen kind
    n_jur: int = 0


def classify_rules(text: str, thread_title: str = "", board: str = "", source: str = "gobe_forum",
                   posted: pd.Timestamp | None = None) -> RuleResult:
    t, _ = prep(text)
    res = RuleResult()
    posted = posted if posted is not None else pd.Timestamp("2020-01-01")
    f = rule_features(text, thread_title, board, source, posted)
    spans = jur_mentions(t)
    res.n_jur = len(spans)
    res.quantity_value, res.quantity_unit = parse_quantity(t, spans)
    res.elev_m = parse_elevation(t)
    res.habitat = parse_habitat(t)
    res.date_offset_days, res.date_uncertainty_days = resolve_date(t, posted)
    if not KIND_MODEL:
        raise RuntimeError("KIND_MODEL is empty: run fit_models() or restore the fitted weights")
    kind, p = _softmax_pick(KIND_MODEL, f)
    res.report_kind, res.score = kind, round(p[kind], 3)
    if kind == "none":
        res.jurcki_outcome = "not_mentioned"
        return res
    res.jurcki_outcome, _ = _softmax_pick(OUTCOME_MODEL, f)
    if res.jurcki_outcome in ("none", "not_mentioned"):
        res.quantity_value = res.quantity_unit = None
    if _OTHER.search(t):
        res.other_mushrooms_outcome = "found"
    if _F_NO_OTHER.search(t):
        res.other_mushrooms_outcome = "none"
    return res


