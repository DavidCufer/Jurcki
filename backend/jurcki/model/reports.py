def resolve_date(t: str, posted: pd.Timestamp) -> tuple[int, int]:
    """(offset in days relative to the post date, uncertainty in days) from relative-date phrases."""
    if re.search(r"\bpredvcerajsnj\w*|\bpred dvema dnevoma\b", t):
        return -2, 1
    if re.search(r"\bvcer(?:aj|ajsnj\w*)\b", t):
        return -1, 0
    m = re.search(r"\bpred (\w+) (?:dnevi|dnevoma|dnem)\b", t)
    if m and m.group(1) in _NUMDAYS:
        return -_NUMDAYS[m.group(1)], 2 if _NUMDAYS[m.group(1)] <= 3 else 3
    m = re.search(r"\bpred (\w+) (?:tedni|tedna|tednoma|tednom)\b", t)
    if m or re.search(r"\bpred tednom\b|\bprejsnji (?:teden|vikend)\b|\bprejsnji teden\b|\bpreteklo? (?:nedeljo|soboto)\b", t):
        n = _NUMDAYS.get(m.group(1), 1) if m else 1
        return -7 * n, 3 if n == 1 else 7
    m = _RE_WD.search(t)
    if m and not re.search(r"\b(?:bom|grem|gremo|gres|greste|jutri|naslednj\w*)\b", t[max(0, m.start() - 40):m.end() + 20]):
        wd = _WD[m.group(1)]
        back = (posted.weekday() - wd) % 7
        return -(back if back else 7), 1
    if re.search(r"\bzadnje dni\b|\bpred nekaj dnevi\b|\bte dni\b", t):
        return -3, 3
    if re.search(r"\bdanes\b|\bdans\b|\bdanasnj\w*|\bzjutraj\b|\bpravkar\b|\bpopoldne\b|\bdopoldne\b|\bzvecer\b", t):
        return 0, 0
    return 0, 1


