def read_labels(labels_dir: Path = LABELS_DIR) -> pd.DataFrame:
    rows = []
    for f in sorted(Path(labels_dir).glob("batch_*.jsonl")):
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.strip():
                rows.append(json.loads(line))
    if not rows:
        return pd.DataFrame(columns=LABEL_FIELDS)
    return pd.DataFrame(rows).drop_duplicates("post_id", keep="last").reset_index(drop=True)


