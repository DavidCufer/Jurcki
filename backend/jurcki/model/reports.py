def rule_location(text: str, min_conf: float = LOC_MIN_CONF):
    """Matcher location of a field report, or None.  Drops origins ('pozdrav iz X', 'doma sem iz X')."""
    from ..geo import geocode
    t = _URL.sub(" ", _QUOTE.sub(" ", text or ""))
    try:
        ms = geocode(t, min_confidence=0.3)
    except Exception:           # defensive: geocoder must never break the whole run
        return None
    ok = [m for m in ms if m.context in ("locative", "around", "none") and m.confidence >= min_conf and "org-prefix" not in m.flags]
    if not ok:
        return None

    def score(m):
        spec = 1.0 - 0.12 * math.log10(max(m.radius_m, 1500) / 1500)
        return m.confidence * spec

    return max(ok, key=score)


_GEO_PREFIX = ("Bil sem v ", "Bil sem na ", "Bil sem pri ", "Bil sem v okolici ")
# Places the labeller named that are missing from (or wrongly fuzzy-matched by) the gazetteer.  Sub-sites of
# the Pohorje are mapped to the whole range (honest, coarse); 'Kope' and 'Kapla' to the gazetteer entries the forum means.
LOC_ALIASES: dict[str, str] = {
    r"sumik\w*": "Pohorje", r"klopn\w* vrh\w*": "Pohorje", r"osankaric\w*": "Pohorje", r"crn\w* jezer\w*": "Pohorje",
    r"kop(?:e|ah|ami)\b": "Velika Kopa", r"kapl(?:a|e|i)\b": "Zgornja Kapla"}
LABEL_LOC_MIN_CONF = 0.4        # a label-text place the matcher is less sure about than this is left without coordinates


def geocode_place(name: str):
    """Geocode a bare place name (labeler-written ``loc_text``).  Tries a few prepositions because the
    matcher needs context to accept a capitalised minor place.  Returns Match or None."""
    from ..geo import geocode
    name = (name or "").replace("_", " ").strip()
    if not name:
        return None
    key = fold(name)
    targets = {tgt for rx, tgt in LOC_ALIASES.items() if re.search(r"\b" + rx, key)}
    alias = len(targets) == 1
    cands = list(targets) if alias else [name] + ([] if " " not in name else [name.split()[0]])
    for cand in cands:
        for pre in _GEO_PREFIX:
            ms = [m for m in geocode(pre + cand + ".", min_confidence=0.2) if m.span[0] >= len(pre) - 1]
            if ms:
                m = max(ms, key=lambda m: m.confidence)
                if alias:
                    m.flags += ("alias",)
                    m.confidence = max(m.confidence, 0.7)
                return m
    return None


def split_id(post_id: str) -> int:
    """Stable 0..2 bucket of a post id; bucket 0 is the held-out set."""
    return int(hashlib.md5(post_id.encode()).hexdigest(), 16) % 3


