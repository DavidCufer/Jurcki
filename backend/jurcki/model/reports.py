def parse_quantity(t: str, mention_spans: list[tuple[int, int]]) -> tuple[float | None, str | None]:
    """kg if a weight is given, else a count that is attached to a jurček word."""
    if _RE_POL.search(t):
        return 0.5, "kg"
    m = _RE_KG.search(t)
    if m:
        v = float(m.group(1).replace(",", "."))
        if 0 < v < 100:
            return v, "kg"
    m = _RE_G.search(t)
    if m:
        v = float(m.group(1).replace(",", ".")) / 1000 * (10 if m.group(2) in ("dkg", "dag") else 1)
        if 0 < v < 20:
            return round(v, 3), "kg"
    best = None
    for m in _RE_COUNT.finditer(t):
        v = int(m.group(1))
        if 1 <= v <= 500:
            d = min([abs(m.start() - e) for _, e in mention_spans] + [abs(m.end() - s) for s, _ in mention_spans] or [999])
            if d <= 60 and (best is None or d < best[0]):
                best = (d, v)
    if best:
        return float(best[1]), "count"
    # '8 lepih jurčkov', 'dva jurčka'
    for s, e in mention_spans:
        w = re.findall(r"[a-z0-9]+", t[max(0, s - 25):s])
        if w:
            x = w[-2] if w[-1] in ("lepih", "mladih", "zdravih", "velikih", "malih", "starih", "lepa", "lepi", "mlada") and len(w) > 1 else w[-1]
            if x.isdigit() and 1 <= int(x) <= 500:
                return float(x), "count"
            if x in _NUMWORDS:
                return float(_NUMWORDS[x]), "count"
    return None, None


def parse_elevation(t: str) -> int | None:
    best = None
    for m in _RE_ELEV.finditer(t):
        a = int(m.group(1))
        b = int(m.group(2)) if m.group(2) else None
        if not (150 <= a <= 2600):
            continue
        # year-like or time like "2018" followed by m? exclude '5 m' and 'xxxx m' preceded by '.'
        if 1900 <= a <= 2100 and not (m.group(0).strip().startswith(("nad", "pod", "okoli", "cca", "ca", "na", "do"))):
            continue
        v = a if b is None else (a + b) // 2
        if best is None:
            best = v
    return best


def parse_habitat(t: str) -> str | None:
    found = [name for name, rx in _HAB if rx.search(t)]
    return ",".join(found[:3]) if found else None


