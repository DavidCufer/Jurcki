def fit_weights(labels_dir: Path = LABELS_DIR, out_path: Path | None = WEIGHTS_PATH, holdout: bool = True,
                n_kind_words: int = 250, n_outcome_words: int = 100) -> dict:
    """Fit the kind / outcome models on the reference labels and write ``reports_weights.py``.

    ``holdout=True`` fits on the development buckets only (``split_id != 0``) so that the agreement numbers of
    ``--eval`` stay honest; ``holdout=False`` uses every labelled post (use after a new labelling round).
    Needs scikit-learn (training only; the classifier itself is plain Python).
    """
    import numpy as np
    import scipy.sparse as sp
    from collections import Counter
    from sklearn.feature_selection import chi2
    from sklearn.linear_model import LogisticRegression

    df = load_sources().set_index("post_id", drop=False)
    lab = read_labels(labels_dir).set_index("post_id", drop=False)
    df = df.loc[df.index.intersection(lab.index)]
    lab = lab.loc[df.index]
    feats = [rule_features(r.text, r.thread_title, r.board, r.source, r.date_posted, use_vocab=False) for _, r in df.iterrows()]
    names = sorted({k for f in feats for k in f})
    X = np.array([[f.get(k, 0.0) for k in names] for f in feats])
    toks = [set(_RE_TOKEN.findall(prep(t)[0])) for t in df.text.values]
    use = np.array([split_id(p) != 0 for p in df.post_id]) if holdout else np.ones(len(df), bool)
    yk = lab.report_kind.astype(object).to_numpy()
    yo = lab.jurcki_outcome.astype(object).to_numpy()
    pos = use & (yk != "none")

    def words(mask, min_df, k, y):
        cnt = Counter(w for m, s in zip(mask, toks) if m for w in s)
        vocab = [w for w, c in cnt.items() if c >= min_df]
        idx = {w: i for i, w in enumerate(vocab)}
        rows, cols = [], []
        for r, s in enumerate(toks):
            for w in s:
                if w in idx:
                    rows.append(r)
                    cols.append(idx[w])
        W = sp.csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(len(toks), len(vocab)))
        sc, _ = chi2(W[mask], y[mask])
        sel = np.argsort(-np.nan_to_num(sc))[:k]
        return [vocab[i] for i in sel], W[:, sel].toarray()

    kw, KW = words(use, 25, n_kind_words, yk != "none")
    ow, OW = words(pos, 20, n_outcome_words, yo)
    km = LogisticRegression(C=1, max_iter=5000).fit(np.hstack([X, KW])[use], yk[use])
    om = LogisticRegression(C=0.3, max_iter=5000).fit(np.hstack([X, OW])[pos], yo[pos])

    def dump(model, nm):
        out = {}
        for c, w, b in zip(model.classes_, model.coef_, model.intercept_):
            d = {n: round(float(v), 3) for n, v in zip(nm, w) if abs(v) >= 0.02 and n != "bias"}
            d["bias"] = round(float(b + w[nm.index("bias")]), 3)
            out[str(c)] = d
        return out

    kind_model = dump(km, names + ["w_" + w for w in kw])
    out_model = dump(om, names + ["w_" + w for w in ow])
    vocab = sorted(set(kw) | set(ow))
    if out_path is not None:
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write('"""Fitted weights of the rule classifier in jurcki.model.reports (generated by ``fit_weights``, do not edit).\n\n'
                     'Multinomial logistic regression on regex features + a small list of common (folded) words, fitted on the\n'
                     'reference labels (development buckets only when holdout=True).  Contains no post text.\n"""\n\n')
            fh.write("VOCAB = frozenset(%r)\n\n" % (vocab,))
            for nm, model in (("KIND_MODEL", kind_model), ("OUTCOME_MODEL", out_model)):
                fh.write(f"{nm} = {{\n")
                for c, d in model.items():
                    fh.write(f"    {c!r}: {d!r},\n")
                fh.write("}\n\n")
    return {"n_fit": int(use.sum()), "vocab": len(vocab), "kind_model": kind_model, "outcome_model": out_model}


