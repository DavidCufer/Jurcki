def jur_mentions(t: str) -> list[tuple[int, int]]:
    """Spans of words that mean jurček in the forum sense (not named non-jurčki 'žametasti goban')."""
    spans = [(m.start(), m.end()) for m in _RE_JUR_STRONG.finditer(t)]
    for m in _RE_GOBAN.finditer(t):
        before = t[max(0, m.start() - 24):m.start()]
        w = re.findall(r"[a-z]+", before)
        if w and re.fullmatch(_NONJ, w[-1]):
            continue
        after = t[m.end():m.end() + 14]
        if re.match(r"\s*(?:ovec|ovc|ovk)", after):    # 'gobanovec' = Gyroporus / unrelated
            continue
        spans.append((m.start(), m.end()))
    for m in _RE_BOLETUS.finditer(t):
        if m.group(1) in _JUR_LATIN and not any(a <= m.start() < b or m.start() <= a < m.end() for a, b in spans):
            spans.append((m.start(), m.end()))
    return sorted(spans)


