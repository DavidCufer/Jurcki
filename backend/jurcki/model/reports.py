_URL = re.compile(r"https?://\S+|www\.\S+|\S+\.(?:jpe?g|png|gif)\b", re.I)
_QUOTE = re.compile(r"\[quote.*?\[/quote\]|\[/?(?:img|url|b|i|color)[^\]]*\]", re.I | re.S)


def prep(text: str) -> tuple[str, bool]:
    """Folded text without urls / bbcode and the has_url flag."""
    t = _QUOTE.sub(" ", text or "")
    has_url = bool(_URL.search(t))
    t = _URL.sub(" ", t)
    return re.sub(r"\s+", " ", fold(t)).strip(), has_url


