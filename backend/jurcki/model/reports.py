def _cnt(rx: re.Pattern, s: str) -> int:
    return len(rx.findall(s))


def rule_features(text: str, thread_title: str = "", board: str = "", source: str = "gobe_forum",
                  posted: pd.Timestamp | None = None, title_hint: bool = True, use_vocab: bool = True) -> dict[str, float]:
    """Sparse numeric features of a post (regex counts); the same features drive the kind and the outcome model."""
    t, has_url = prep(text)
    f: dict[str, float] = {}
    posted = posted if posted is not None else pd.Timestamp("2020-01-01")
    season = thread_is_season(thread_title)
    ident_thread = thread_is_ident(thread_title) and not season
    news = source in ("svet24", "n1", "siol")
    spans = jur_mentions(t)
    f["bias"] = 1.0
    f["len"] = min(math.log1p(len(t)) / 6.0, 1.5)
    f["short"] = float(len(t) < 40)
    f["season"] = float(season)
    f["ident_thread"] = float(ident_thread)
    f["news"] = float(news)
    f["slotech"] = float(source == "slotech")
    f["year17"] = float(posted.year >= 2017)
    f["url"] = float(has_url)
    f["photo_only"] = float(has_url and len(t) < 160)
    f["photo_only_y17"] = f["photo_only"] * f["year17"] * f["season"]
    f["photo_only_old"] = f["photo_only"] * (1 - f["year17"]) * f["season"]
    f["q"] = min(text.count("?"), 3) / 3.0
    f["n_jur"] = min(len(spans), 5) / 5.0
    f["has_jur"] = float(bool(spans))
    n_other = _cnt(_OTHER, t)
    f["has_other"] = float(n_other > 0)
    f["n_other"] = min(n_other, 6) / 6.0
    f["gen_neg"] = float(bool(_GEN_NEG.search(t)))
    f["mush"] = float(bool(re.search(r"\bgob\w*", t)))
    f["strict"] = min(_cnt(_F_STRICT, t), 4) / 4.0
    f["strict1"] = float(bool(_F_STRICT.search(t)))
    f["loose"] = float(bool(_F_LOOSE.search(t)))
    f["time"] = float(bool(_F_TIME.search(t)))
    f["recall"] = float(bool(_F_RECALL.search(t)))
    f["future"] = float(bool(_F_FUTURE.search(t)))
    f["greet"] = float(bool(_F_GREET.match(t)))
    f["congr"] = float(bool(_F_CONGRATS.search(t)))
    f["addr"] = min(_cnt(_F_ADDR, t), 4) / 4.0
    f["ask"] = float(bool(_F_ASK.search(t)))
    f["ident_q"] = float(bool(_QUESTION_IDENT.search(t)))
    f["noise"] = min(_cnt(_F_NOISE, t), 4) / 4.0
    f["third"] = float(bool(_F_THIRD.search(t)))
    f["third_act"] = float(bool(_F_THIRD.search(t)) and bool(_F_THIRD_ACT.search(t)))
    f["present"] = float(bool(_F_PRESENT.search(t)))
    f["region"] = float(bool(_F_REGION.search(t)))
    f["first_of_season"] = float(bool(_F_FIRSTSEASON.search(t)) or bool(_F_FIRST_BOL.search(t)))
    f["num"] = min(_cnt(_F_NUM, t), 6) / 6.0
    q_val, q_unit = parse_quantity(t, spans)
    f["q_count"] = float(q_unit == "count")
    f["q_kg"] = float(q_unit == "kg")
    f["elev"] = float(parse_elevation(t) is not None)
    f["was"] = float(bool(_F_WAS.search(t)))
    f["duration"] = float(bool(_F_DURATION.search(t)))
    f["nic"] = float(bool(_F_NIC.search(t)))
    f["heard"] = float(bool(_F_HEARD.search(t)))
    f["nothing_else"] = float(bool(_F_NOTHING_ELSE.search(t)))
    f["dry"] = float(bool(_F_DRY.search(t)))
    f["zero"] = float(bool(_F_ZERO.search(t)))
    f["none_implied"] = float(bool(_F_NOTHING_ELSE.search(t) or _F_ZERO.search(t) or _F_SAMO_OTHER.search(t)))
    f["short_season"] = float(len(t) < 90 and season)
    f["short_season_nic"] = f["short_season"] * f["nic"]
    f["short_season_place"] = 0.0
    f["loc_mention"] = 0.0
    if title_hint:
        try:
            from ..geo import geocode
            ms = geocode(_URL.sub(" ", text or ""), min_confidence=0.5)
            ms = [m for m in ms if m.context in ("locative", "around", "none")]
            f["loc_mention"] = float(bool(ms))
            f["short_season_place"] = f["short_season"] * f["loc_mention"]
        except Exception:
            pass
    # clause-level jurček evidence
    n_neg = n_pos = n_few = n_many = n_old = n_young = 0
    for a, b in _clauses(t):
        c = t[a:b]
        if not any(a <= s < b for s, _ in spans):
            continue
        neg = False
        if _NEG_NEAR.search(c):
            c2 = re.sub(r"\b(?:ni|niso|ne)\s+(?:zelo |tako |prav |kaj |preveč |prevec )?(?:crviv\w*|grenk\w*|greni|stari|star|slab\w*|"
                        r"majhn\w*|mal\w*|zamenj\w*|zahtevn\w*|poceni|draga?|problem\w*|nevarn\w*|strup\w*|uzitn\w*)", " ", c)
            neg = bool(_NEG_NEAR.search(c2))
        if neg:
            n_neg += 1
        else:
            n_pos += 1
            n_few += bool(_FEW.search(c))
            n_many += bool(_MANY.search(c))
            n_old += bool(_OLD.search(c))
            n_young += bool(_YOUNG.search(c))
    f["jneg"] = min(n_neg, 3) / 3.0
    f["jpos"] = min(n_pos, 3) / 3.0
    f["jneg_only"] = float(n_neg > 0 and n_pos == 0)
    f["jfew"] = float(n_few > 0)
    f["jmany"] = float(n_many > 0)
    f["jold"] = float(n_old > 0)
    f["jyoung"] = float(n_young > 0)
    f["jold_only"] = float(n_old > 0 and n_young == 0)
    f["samo_other"] = float(bool(_F_SAMO_OTHER.search(t)))
    f["no_other"] = float(bool(_F_NO_OTHER.search(t)))
    f["qty_big"] = float((q_unit == "count" and (q_val or 0) >= 20) or (q_unit == "kg" and (q_val or 0) >= 2.5))
    f["qty_small"] = float((q_unit == "count" and (q_val or 0) <= 5) or (q_unit == "kg" and (q_val or 0) < 1))
    f["qty_mid"] = float((q_unit == "count" and 5 < (q_val or 0) < 20) or (q_unit == "kg" and 1 <= (q_val or 0) < 2.5))
    f["jpos_many"] = f["jpos"] * f["jmany"]
    f["jpos_few"] = f["jpos"] * f["jfew"]
    f["jur_not_neg_nor_pos"] = float(bool(spans) and n_neg == 0 and n_pos == 0)
    if use_vocab:
        for w in set(_RE_TOKEN.findall(t)) & VOCAB:
            f["w_" + w] = 1.0
    return f


