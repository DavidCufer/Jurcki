_SENT = re.compile(r"[.!?;\n]+|\s-\s|\s\|\s|:\s")


def _clauses(t: str) -> list[tuple[int, int]]:
    spans, last = [], 0
    for m in _SENT.finditer(t):
        if m.start() > last:
            spans.append((last, m.start()))
        last = m.end()
    if last < len(t):
        spans.append((last, len(t)))
    return spans


