def rules_vs_labels(labels_dir: Path = LABELS_DIR, posts_path: Path = POSTS_PATH, news_path: Path = NEWS_PATH,
                    with_location: bool = True) -> pd.DataFrame:
    """Rule predictions next to the reference labels for every labelled post (+ split bucket 0/1/2)."""
    df = load_sources(posts_path, news_path).set_index("post_id", drop=False)
    labels = read_labels(labels_dir).set_index("post_id", drop=False)
    df = df.loc[df.index.intersection(labels.index)]
    rows = []
    for pid, r in df.iterrows():
        x = classify_rules(r.text, r.thread_title, r.board, r.source, r.date_posted)
        lab = labels.loc[pid]
        rec = dict(post_id=pid, split=split_id(pid), year=r.date_posted.year,
                   kind_l=lab.report_kind, kind_r=x.report_kind, out_l=lab.jurcki_outcome, out_r=x.jurcki_outcome,
                   oth_l=lab.other_mushrooms_outcome, oth_r=x.other_mushrooms_outcome,
                   qty_l=lab.quantity_value, qty_r=x.quantity_value, qu_l=lab.quantity_unit, qu_r=x.quantity_unit,
                   elev_l=lab.elev_m, elev_r=x.elev_m, off_l=lab.date_offset_days, off_r=x.date_offset_days,
                   locmode_l=lab.loc_mode)
        if with_location and (lab.report_kind != "none" or x.report_kind != "none"):
            lm = None
            if lab.loc_mode == "matcher":
                from ..geo import best_location
                lm = best_location(r.text)
            elif lab.loc_mode == "text":
                lm = geocode_place(lab.loc_text)
                if lm is not None and lm.confidence < LABEL_LOC_MIN_CONF:
                    lm = None
            rm = rule_location(r.text)
            rec.update(lab_lon=lm.lon if lm else float("nan"), lab_lat=lm.lat if lm else float("nan"),
                       lab_rad=lm.radius_m if lm else float("nan"),
                       rule_lon=rm.lon if rm else float("nan"), rule_lat=rm.lat if rm else float("nan"),
                       rule_rad=rm.radius_m if rm else float("nan"), rule_conf=rm.confidence if rm else float("nan"))
        rows.append(rec)
    return pd.DataFrame(rows)


def _km_between(lat1, lon1, lat2, lon2):
    import numpy as np
    return np.hypot((lat1 - lat2) * 111.2, (lon1 - lon2) * 111.2 * np.cos(np.radians((lat1 + lat2) / 2)))


def agreement(cmp: pd.DataFrame) -> dict:
    """Agreement numbers (dict) for one slice of ``rules_vs_labels``."""
    import numpy as np
    out: dict = {"n": int(len(cmp))}
    lb, pb = cmp.kind_l != "none", cmp.kind_r != "none"
    tp, fp, fn = int((lb & pb).sum()), int((~lb & pb).sum()), int((lb & ~pb).sum())
    out.update(report_precision=tp / max(tp + fp, 1), report_recall=tp / max(tp + fn, 1), report_f1=2 * tp / max(2 * tp + fp + fn, 1),
               kind_acc4=float((cmp.kind_l == cmp.kind_r).mean()), n_labelled_reports=int(lb.sum()))
    both = cmp[lb & pb]
    out["outcome_acc_both"] = float((both.out_l == both.out_r).mean()) if len(both) else float("nan")
    co = lambda s: s.map({"found": "present", "few": "present", "many": "present", "none": "none"}).fillna("other")
    out["outcome_coarse_acc_both"] = float((co(both.out_l) == co(both.out_r)).mean()) if len(both) else float("nan")
    out["outcome_acc_labelled_reports"] = float((cmp[lb].out_l == cmp[lb].out_r).mean()) if lb.any() else float("nan")
    # absence recall: labelled 'none' reports detected as none
    ln = cmp[lb & (cmp.out_l == "none")]
    out["none_recall"] = float((ln.out_r == "none").mean()) if len(ln) else float("nan")
    pn = cmp[pb & (cmp.out_r == "none")]
    out["none_precision"] = float((pn.out_l == "none").mean()) if len(pn) else float("nan")
    ob = cmp[lb & pb]
    out["other_acc_both"] = float((ob.oth_l == ob.oth_r).mean()) if len(ob) else float("nan")
    if "lab_lon" in cmp:
        has_l, has_r = ~cmp.lab_lon.isna(), ~cmp.rule_lon.isna()
        both_loc = cmp[has_l & has_r]
        d = _km_between(both_loc.lab_lat, both_loc.lab_lon, both_loc.rule_lat, both_loc.rule_lon)
        out.update(loc_labelled=int((has_l & lb).sum()), loc_rule_found_of_labelled=float((has_l & has_r).sum() / max(has_l.sum(), 1)),
                   loc_rule_precision_presence=float((has_l & has_r).sum() / max(has_r.sum(), 1)),
                   loc_within_10km=float((d <= 10).mean()) if len(d) else float("nan"),
                   loc_within_30km=float((d <= 30).mean()) if len(d) else float("nan"),
                   loc_median_km=float(np.median(d)) if len(d) else float("nan"))
    qb = cmp[lb & pb & cmp.qty_l.notna()]
    out["qty_detect_recall"] = float(qb.qty_r.notna().mean()) if len(qb) else float("nan")
    qq = qb[qb.qty_r.notna() & (qb.qu_l == qb.qu_r)]
    out["qty_exact_given_same_unit"] = float((qq.qty_l.astype(float) == qq.qty_r.astype(float)).mean()) if len(qq) else float("nan")
    eb = cmp[lb & cmp.elev_l.notna()]
    out["elev_recall"] = float(eb.elev_r.notna().mean()) if len(eb) else float("nan")
    ee = eb[eb.elev_r.notna()]
    out["elev_within_100m"] = float(((ee.elev_l.astype(float) - ee.elev_r.astype(float)).abs() <= 100).mean()) if len(ee) else float("nan")
    db = cmp[lb & pb]
    out["date_offset_exact"] = float((db.off_l == db.off_r).mean()) if len(db) else float("nan")
    out["date_offset_within1"] = float(((db.off_l - db.off_r).abs() <= 1).mean()) if len(db) else float("nan")
    return out


def format_agreement(cmp: pd.DataFrame, title: str) -> str:
    a = agreement(cmp)
    lines = [f"== {title} (n={a['n']}, labelled reports={a['n_labelled_reports']})"]
    for k, v in a.items():
        if k in ("n", "n_labelled_reports"):
            continue
        lines.append(f"  {k:32s} {v:.3f}" if isinstance(v, float) else f"  {k:32s} {v}")
    lines.append("  kind confusion (rows = reference label, cols = rules):")
    lines.append(pd.crosstab(cmp.kind_l, cmp.kind_r).to_string().replace("\n", "\n    "))
    lb = cmp[(cmp.kind_l != "none") & (cmp.kind_r != "none")]
    lines.append("  jurcki_outcome confusion where both call it a report (rows = reference):")
    lines.append(pd.crosstab(lb.out_l, lb.out_r).to_string().replace("\n", "\n    "))
    return "\n".join(lines)


# --- summary -------------------------------------------------------------------------------------------------
def _d(series: pd.Series) -> dict:
    return {k: int(v) for k, v in series.items()}


def summarize(rep: pd.DataFrame) -> str:
    """Counts by year x outcome, region, month, usable locations and example paraphrases (text report)."""
    out: list[str] = []
    r = rep.copy()
    r["year"] = pd.to_datetime(r["date_observed"]).dt.year
    r["month"] = pd.to_datetime(r["date_observed"]).dt.month
    out.append(f"field reports: {len(r)} (labeler: {_d(r.labeler.value_counts())}); kinds: {_d(r.report_kind.value_counts())}")
    out.append("\njurcki_outcome by observation year (all report kinds):")
    out.append(pd.crosstab(r.year, r.jurcki_outcome).reindex(columns=[c for c in OUTCOMES if c in set(r.jurcki_outcome)]).to_string())
    pos = r[r.jurcki_outcome.isin(["found", "few", "many"])]
    neg = r[r.jurcki_outcome == "none"]
    yy = pd.DataFrame({"present": pos.groupby("year").size(), "none": neg.groupby("year").size()}).fillna(0).astype(int)
    yy["share_none"] = (yy["none"] / (yy["present"] + yy["none"]).clip(lower=1)).round(2)
    out.append("\nabsence share per year (none / (present + none)):")
    out.append(yy.to_string())
    out.append("\njurcki_outcome by month (all years):")
    out.append(pd.crosstab(r.month, r.jurcki_outcome).to_string())
    loc = r[r.loc_lon.notna()]
    out.append(f"\nusable location: {len(loc)} of {len(r)} ({len(loc) / max(len(r), 1):.0%}); by source: {_d(loc.loc_source.value_counts())}")
    if len(loc):
        q = loc.loc_radius_m.quantile([0.1, 0.25, 0.5, 0.75, 0.9]).round(0)
        out.append("  radius_m quantiles 10/25/50/75/90%: " + " / ".join(str(int(v)) for v in q))
        bins = pd.cut(loc.loc_radius_m, [0, 2000, 5000, 10000, 20000, 1e9], labels=["<=2 km", "2-5 km", "5-10 km", "10-20 km", ">20 km"])
        out.append("  radius classes: " + str(_d(bins.value_counts().sort_index())))
        out.append("  location kind: " + str(_d(loc.loc_kind.value_counts())))
        out.append("\nreports by statistical region (nearest centre) x outcome:")
        out.append(pd.crosstab(loc.region, loc.jurcki_outcome).assign(total=lambda d: d.sum(axis=1)).sort_values("total", ascending=False).to_string())
    out.append(f"\nelevation stated: {int(r.elev_m.notna().sum())}; quantity stated: {int(r.quantity_value.notna().sum())}; "
               f"habitat stated: {int(r.habitat.notna().sum())}")
    ex = r[(r.labeler == "llm") & (r.paraphrase.str.len() > 0)]
    if len(ex):
        out.append("\nexample paraphrases (reference labels):")
        for o in ("none", "few", "found", "many"):
            e = ex[ex.jurcki_outcome == o]
            for _, x in e.sample(min(3, len(e)), random_state=1).iterrows():
                out.append(f"  [{o:5s} {pd.Timestamp(x.date_observed):%Y-%m-%d} {x.loc_name if isinstance(x.loc_name, str) else '-'}] {x.paraphrase}")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m jurcki.model.reports",
                                 description="Rebuild data/processed/field_reports.parquet: reference (llm) labels where "
                                             "present, rule classifier everywhere else.  No network.")
    ap.add_argument("--no-labels", action="store_true", help="ignore the reference labels; rules only")
    ap.add_argument("--eval", action="store_true", help="print rules-vs-labels agreement (dev and held-out split)")
    ap.add_argument("--refit", action="store_true",
                    help="refit reports_weights.py on the reference labels (dev buckets only unless --refit-all); needs scikit-learn")
    ap.add_argument("--refit-all", action="store_true", help="like --refit but on every labelled post")
    ap.add_argument("--out", type=Path, default=OUT_PATH)
    ap.add_argument("--summary", type=Path, default=PROCESSED / "field_reports_summary.txt")
    ap.add_argument("-q", "--quiet", action="store_true")
    a = ap.parse_args(argv)
    if not (POSTS_PATH.exists() or NEWS_PATH.exists()):
        print(f"no input: {POSTS_PATH} / {NEWS_PATH} missing (run the web build first)", file=sys.stderr)
        return 2
    if a.refit or a.refit_all:
        info = fit_weights(holdout=not a.refit_all)
        print(f"refitted {WEIGHTS_PATH.name} on {info['n_fit']} labelled posts, {info['vocab']} words; restart to load")
        return 0
    rep = build_reports(use_labels=not a.no_labels, out_path=a.out, verbose=not a.quiet)
    print(f"wrote {a.out}: {len(rep)} field reports "
          f"({int((rep.labeler == 'llm').sum())} reference-labelled, {int((rep.labeler == 'rules').sum())} rule-classified)")
    txt = summarize(rep)
    a.summary.write_text(txt + "\n", encoding="utf-8")
    if not a.quiet:
        print(txt)
    if a.eval:
        cmp = rules_vs_labels()
        print(format_agreement(cmp[cmp.split != 0], "development split (buckets 1,2)"))
        print(format_agreement(cmp[cmp.split == 0], "held-out split (bucket 0)"))
    return 0


if __name__ == "__main__":      # pragma: no cover
    sys.exit(main())
